                    <article class="portal-phase-guide__item">
                        <span class="portal-phase-guide__number">1</span>
                        <div>
                            <h6>Participación ciudadana</h6>
                            <p>Esta fase inicia el proceso de elaboración del POU, incluyendo los objetivos, plazos, actores implicados y formas de participación. Se define la metodología de trabajo interdisciplinar entre los técnicos redactores, los responsables políticos y los ciudadanos. Además, se plantea un plan específico de participación pública que recoge acciones como encuestas, reuniones vecinales, buzones de sugerencias, sesiones informativas, herramientas digitales y mecanismos de retroalimentación continua.</p>
                        </div>
                    </article>

                    <article class="portal-phase-guide__item">
                        <span class="portal-phase-guide__number">2</span>
                        <div>
                            <h6>Documento de Avance del POU</h6>
                            <p>Se realiza una recopilación exhaustiva de datos sobre la realidad actual del municipio, abarcando aspectos físicos, demográficos, ambientales, sociales, económicos y funcionales. Incluye análisis urbano y territorial, redes de infraestructuras, dotaciones, riesgos, medio ambiente y patrimonio. Se elabora cartografía temática y estudios sectoriales, todo ello enfocado a identificar las debilidades, amenazas, fortalezas y oportunidades que servirán como base para la propuesta. La redacción del Avance del Plan recoge una primera propuesta de ordenación del territorio municipal con diferentes alternativas, incorporando criterios de sostenibilidad, equilibrio territorial y compatibilidad con la normativa vigente. Paralelamente, se elabora el Documento Inicial Estratégico (DIE), que inicia el procedimiento de Evaluación Ambiental Estratégica.</p>
                        </div>
                    </article>

                    <article class="portal-phase-guide__item">
                        <span class="portal-phase-guide__number">3</span>
                        <div>
                            <h6>Acuerdo municipal y publicación web del Avance del POU</h6>
                            <p>Una vez elaborado el documento de Avance del POU y su Documento Inicial Estratégico, se somete a revisión técnica y legal. Tras su validación, se eleva a Acuerdo Municipal del Ayuntamiento, teniendo efectos administrativos internos y preparatorios. El Avance del POU y su Documento Inicial Estratégico se publican en la web municipal para que la ciudadanía pueda conocer su contenido y presentar sugerencias al modelo de planificación previsto. Posteriormente se tramita ambientalmente el Avance con el objetivo de obtener el Documento de Alcance, y se solicita el informe relativo a la Valoración de Impacto en Salud.</p>
                        </div>
                    </article>

                    <article class="portal-phase-guide__item">
                        <span class="portal-phase-guide__number">4</span>
                        <div>
                            <h6>Documento de aprobación inicial del POU</h6>
                            <p>Se elabora el documento para la Aprobación Inicial del POU, que incluye memorias, normativa urbanística, cartografía y anexos, incorporando las directrices establecidas por las Consejerías competentes en materia de Medio Ambiente y de Salud.</p>
                        </div>
                    </article>

                    <article class="portal-phase-guide__item">
                        <span class="portal-phase-guide__number">5</span>
                        <div>
                            <h6>Aprobación inicial del POU e información pública</h6>
                            <p>El documento se somete a revisión técnica y legal y, tras su validación, se eleva al Pleno del Ayuntamiento para su aprobación inicial. Esta aprobación no supone su entrada en vigor, pero permite continuar el proceso de participación pública. Se abre un periodo de exposición pública no inferior a 45 días, durante el cual ciudadanos, colectivos, asociaciones, colegios profesionales y otras administraciones pueden consultar el documento y presentar alegaciones. Todas las contestaciones se incorporarán en la Memoria de Participación del Plan. Asimismo, se podrán suspender autorizaciones y licencias en áreas concretas y se solicitarán los informes sectoriales preceptivos.</p>
                        </div>
                    </article>

                    <article class="portal-phase-guide__item">
                        <span class="portal-phase-guide__number">6</span>
                        <div>
                            <h6>Documento de Propuesta Final del POU</h6>
                            <p>El órgano ambiental autonómico emite la Declaración Ambiental Estratégica (DAE) tras analizar el documento aprobado inicialmente. La DAE puede establecer condiciones y medidas correctoras de obligado cumplimiento, que se integrarán en la Propuesta Final del Plan. El documento se revisa incorporando el resultado del trámite de información pública, los requerimientos de la DAE y los informes sectoriales emitidos, garantizando el cumplimiento de los principios de desarrollo sostenible y preservación del medio natural.</p>
                        </div>
                    </article>

                    <article class="portal-phase-guide__item">
                        <span class="portal-phase-guide__number">7</span>
                        <div>
                            <h6>Aprobación definitiva del POU</h6>
                            <p>El POU se aprueba de forma definitiva por el órgano competente del Ayuntamiento. En esta fase el documento adquiere carácter normativo, aunque todavía está pendiente su publicación oficial.</p>
                        </div>
                    </article>

                    <article class="portal-phase-guide__item">
                        <span class="portal-phase-guide__number">8</span>
                        <div>
                            <h6>Publicación en BOJA del POU y entrada en vigor</h6>
                            <p>Tras la aprobación definitiva, el POU se publica en el Boletín Oficial de la Junta de Andalucía (BOJA). A partir de ese momento entra en vigor y se convierte en la normativa urbanística de referencia para todo el término municipal. Se inscribe en el Registro de Instrumentos de Planeamiento Urbanístico y se inicia su divulgación, poniéndose a disposición pública en la web municipal y en soporte físico.</p>
                        </div>
                    </article>
